class AiService {
    public static function analyzeTicket($subject, $message) {
        // Redefined URL and Key internally to ensure they exist within the class scope
        $apiKey = 'AIzaSyCRXbcnAZCifu8Z949XSbzc8yO2rmLhvEw'; 
        $url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=" . $apiKey;

        // Structured prompt to eliminate AI ambiguity regarding medical severity
        $prompt = "You are an AI support assistant for a critical blood donation network.\n" .
                  "Analyze this support ticket and determine its priority (Low, Medium, or High) and draft a response.\n\n" .
                  "CRITICAL PRIORITY RULES:\n" .
                  "- If the message mentions medical symptoms, an emergency hospital scenario, surgery, an ongoing health crisis, or immediate need for blood, you MUST set the priority to 'High'.\n" .
                  "- General inquiries are Medium or Low.\n\n" .
                  "Subject: $subject\n" .
                  "Message: $message\n\n" .
                  "Respond ONLY with a valid JSON object matching this schema exactly. Do not wrap it in markdown block quotes:\n" .
                  "{\n" .
                  "  \"priority\": \"Low\" | \"Medium\" | \"High\",\n" .
                  "  \"draft\": \"Your response here\"\n" .
                  "}";

        $payload = [
            "contents" => [
                [
                    "parts" => [
                        ["text" => $prompt]
                    ]
                ]
            ]
        ];

        $ch = curl_init($url);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_POST, true);
        curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode($payload));
        curl_setopt($ch, CURLOPT_HTTPHEADER, ['Content-Type: application/json']);
        
        // Local environment SSL bypass rules
        curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, false); 
        curl_setopt($ch, CURLOPT_SSL_VERIFYHOST, false);
        
        $response = curl_exec($ch);
        
        if (curl_errno($ch)) {
            curl_close($ch);
            return ['priority' => 'High', 'draft' => 'Connection fallback occurred. Verification needed.'];
        }
        
        curl_close($ch);
        $data = json_decode($response, true);

        if (isset($data['candidates'][0]['content']['parts'][0]['text'])) {
            $rawText = trim($data['candidates'][0]['content']['parts'][0]['text']);
            
            // Clean up backticks or structural markdown variations generated by the AI
            $rawText = str_replace(['```json', '```'], '', $rawText);
            
            $result = json_decode(trim($rawText), true);
            if ($result && isset($result['priority'])) {
                // Ensure the exact capitalization matches what our ENUM columns require
                $result['priority'] = ucfirst(strtolower(trim($result['priority'])));
                return $result;
            }
        }

        // If something completely unexpected happens, safely assume High for health screening
        return ['priority' => 'High', 'draft' => 'Automatic review could not parse data. Immediate attention required.'];
    }
}
